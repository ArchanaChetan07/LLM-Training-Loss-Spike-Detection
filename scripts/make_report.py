"""Build results/RESULTS.md from results/olmo_eval.json and results/small_eval.json.

Every number in the README's results section comes from here (no hand transcription).
Window false-alarm rates get exact Clopper-Pearson 95% intervals; the endpoint is
judged on the point estimate exactly as pre-registered, the interval is context.
"""

from __future__ import annotations

import json
from pathlib import Path

from scipy.stats import beta

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
HELD_OUT = ["OLMo-1B", "OLMo-7B", "OLMo-1.7-7B", "OLMo-2-7B"]


def cp(k, n, a=0.05):
    if not n:
        return (float("nan"), float("nan"))
    lo = 0.0 if k == 0 else beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(1 - a / 2, k + 1, n - k)
    return lo, hi


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}%"


def lead(x):
    return "–" if x is None else f"{x:+.0f}"


def wfa(r):
    k, n = r.get("windows_with_fa"), r.get("windows")
    if n is None:  # per-series summaries store the rate + count of stable windows implicitly
        return pct(r["window_fa_rate"])
    lo, hi = cp(k, n)
    return f"{pct(r['window_fa_rate'])} ({k}/{n}; CI {100*lo:.1f}–{100*hi:.1f}%)"


def row(name, r):
    return (f"| {name} | {r['events']} | {r['detected']} | {r['detected_ahead_of_onset']} | "
            f"{lead(r.get('median_lead_onset'))} | {lead(r.get('median_lead_peak'))} | {wfa(r)} |")


HDR = ("| | spikes M | detected N | ≥1 step before onset | median lead to onset | median lead to peak | "
       "window FA rate |\n|---|---|---|---|---|---|---|")


def main():
    o = json.loads((RES / "olmo_eval.json").read_text())
    lines = ["# Results (generated by scripts/make_report.py)", ""]
    lines += ["## Primary endpoint: G-rate e-detector on held-out OLMo series", "", HDR]
    verdict, tot = [], {"M": 0, "ahead": 0}
    for s in HELD_OUT:
        if s not in o["series"]:
            lines.append(f"| {s} | not available | | | | | |"); continue
        g = o["series"][s]["test"]["G-rate"]
        lines.append(row(s + (" (steps > 250k)" if s == "OLMo-1B" else ""), g))
        verdict.append((s, g["window_fa_rate"]))
        tot["M"] += g["events"]; tot["ahead"] += g["detected_ahead_of_onset"]
    fa_ok = all(x is not None and x <= 0.05 for _, x in verdict)
    frac = tot["ahead"] / tot["M"] if tot["M"] else float("nan")
    lines += ["", f"* FA ≤ 5% on every held-out series: **{'yes' if fa_ok else 'no'}** "
                  f"({', '.join(f'{s} {pct(x)}' for s, x in verdict)})",
              f"* Pooled N_ahead / M = {tot['ahead']}/{tot['M']} = {pct(frac)} (pre-registered bar: ≥ 50%)",
              f"* **Pre-registered success: {'MET' if fa_ok and frac >= 0.5 else 'NOT MET'}**"
              + ("" if fa_ok else " — falsified on the FA criterion (guarantee did not transfer everywhere)"), ""]

    lines += ["## Calibration split (OLMo-1B steps 10k–250k; in-sample for ρ and baseline tuning)", "", HDR]
    for k, v in o["series"]["OLMo-1B"]["calibration"].items():
        lines.append(row(k, v))

    lines += ["", "## Held-out comparison: every configuration", ""]
    for s in HELD_OUT:
        if s not in o["series"]:
            continue
        lines += [f"### {s}", "", HDR]
        for k, v in o["series"][s]["test"].items():
            lines.append(row(k, v))
        lines.append("")

    lines += ["## Tuned baselines", "", f"z threshold k = {o['tuned']['z']}, CUSUM h = {o['tuned']['cusum']} "
              "(most sensitive setting with window FA ≤ 5% on the calibration split).", ""]

    sp = RES / "small_eval.json"
    if sp.exists():
        sm = json.loads(sp.read_text())
        lines += ["## Own runs (small Post-LN GPT sweep; ρ fitted on 5 lr=1e-3 controls, 24 test runs)", "", HDR]
        for k, v in sm["configs"].items():
            lines.append(row(k, v["test"]))
        lines.append("")
    (RES / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {RES / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
